const { before, after, beforeEach, test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const { initializeTestEnvironment, assertSucceeds, assertFails } = require('@firebase/rules-unit-testing')
const { doc, getDoc, getDocs, collection, setDoc, updateDoc, deleteDoc, serverTimestamp } = require('firebase/firestore')
const load = require('./load-ts.cjs')
const { coursesInLevel } = load('lib/islamic/curriculum.ts')
const { issueCertificate } = load('lib/islamic/certificates.ts')
let env
before(async()=>{env=await initializeTestEnvironment({projectId:'demo-samee3',firestore:{host:'127.0.0.1',port:8088,rules:fs.readFileSync('firestore.rules','utf8')}})})
after(async()=>{if(env)await env.cleanup()})
beforeEach(async()=>{await env.clearFirestore()})
const user=(id='learner')=>env.authenticatedContext(id,{email:`${id}@example.test`}).firestore()
const saveProgress=(db,ids,uid='learner')=>setDoc(doc(db,'users',uid,'libraryProgress','state'),{version:1,completedBookIds:ids,updatedAt:serverTimestamp()})
const complete=(db,level='beginner')=>saveProgress(db,coursesInLevel(level).map(x=>x.id))
test('owner progress is private and unrecognized curriculum IDs are rejected',async()=>{
 const db=user();await assertSucceeds(complete(db));await assertFails(getDoc(doc(user('other'),'users','learner','libraryProgress','state')))
 await assertFails(saveProgress(db,['invented-course']));await assertFails(getDoc(doc(env.unauthenticatedContext().firestore(),'users','learner','libraryProgress','state')))
})
test('a certificate cannot be created before completing the level',async()=>{
 const db=user();await saveProgress(db,[coursesInLevel('beginner')[0].id]);await assert.rejects(()=>issueCertificate(db,'learner','beginner','طالب علم'))
 assert.equal((await getDocs(collection(db,'users','learner','libraryCertificates'))).size,0)
})
test('concurrent issuance resolves to one immutable certificate and one name',async()=>{
 const db=user();await complete(db)
 const [a,b]=await Promise.all([issueCertificate(db,'learner','beginner','الاسم الأول'),issueCertificate(db,'learner','beginner','الاسم الثاني')])
 assert.equal(a.serial,b.serial);assert.equal(a.name,b.name)
 const ref=doc(db,'users','learner','libraryCertificates','beginner')
 await assertFails(updateDoc(ref,{name:'اسم بديل'}));await assertFails(deleteDoc(ref))
 assert.equal((await getDocs(collection(db,'users','learner','libraryCertificates'))).size,1)
 const third=await issueCertificate(db,'learner','beginner','اسم ثالث');assert.equal(third.serial,a.serial);assert.equal(third.name,a.name)
})
test('rules enforce completion even when a client bypasses the application',async()=>{
 const db=user();await saveProgress(db,[])
 const data={levelId:'beginner',name:'طالب علم',serial:'SM3-BEG-1234ABCD',courseIds:coursesInLevel('beginner').map(x=>x.id),curriculumVersion:1,issuedAt:serverTimestamp()}
 await assertFails(setDoc(doc(db,'users','learner','libraryCertificates','beginner'),data))
 await complete(db)
 await assertFails(setDoc(doc(db,'users','learner','libraryCertificates','beginner-copy'),data))
 await assertFails(setDoc(doc(db,'users','learner','libraryCertificates','advanced'),{...data,levelId:'advanced'}))
 await assertSucceeds(setDoc(doc(db,'users','learner','libraryCertificates','beginner'),data))
 await assertFails(getDoc(doc(user('other'),'users','learner','libraryCertificates','beginner')))
})
test('ayah notes sync for the owner and reject oversized or foreign writes',async()=>{
 const db=user(),ref=doc(db,'users','learner','ayahStudy','2_255')
 await assertSucceeds(setDoc(ref,{note:'ملاحظة خاصة',reviewCount:1,memorized:true,updatedAt:serverTimestamp()}))
 const sousi=doc(db,'users','learner','ayahStudy','sousi_2_5')
 await assertSucceeds(setDoc(sousi,{note:'ملاحظة السوسي مستقلة',reviewCount:0,memorized:false,updatedAt:serverTimestamp()}))
 assert.equal((await getDoc(ref)).data().note,'ملاحظة خاصة')
 await assertFails(setDoc(doc(db,'users','learner','ayahStudy','invented_2_5'),{note:'x',reviewCount:0,memorized:false,updatedAt:serverTimestamp()}))
 await assertFails(updateDoc(ref,{note:'ن'.repeat(4001),updatedAt:serverTimestamp()}))
 await assertFails(getDoc(doc(user('other'),'users','learner','ayahStudy','2_255')))
})
test('regular accounts cannot self-promote to admin',async()=>{
 const db=user(),ref=doc(db,'users','learner')
 await assertSucceeds(setDoc(ref,{name:'طالب علم',displayName:'طالب علم',email:'learner@example.test',role:'user',status:'active',createdAt:serverTimestamp(),updatedAt:serverTimestamp(),lastLoginAt:serverTimestamp()}))
 await assertFails(updateDoc(ref,{role:'admin'}))
 await assertSucceeds(updateDoc(ref,{name:'اسم محدث',displayName:'اسم محدث',lastLoginAt:serverTimestamp(),updatedAt:serverTimestamp()}))
})

test('conversation messages and receipts reject foreign reads and sender spoofing',async()=>{
 const db=user(),reference=doc(db,'conversations','learner','messages','message-1')
 const data={senderId:'learner',senderName:'اسم الطالب',text:'رسالة تجريبية محلية',createdAt:serverTimestamp(),read:false}
 await assertSucceeds(setDoc(reference,data))
 await assertFails(getDoc(doc(user('other'),'conversations','learner','messages','message-1')))
 await assertFails(setDoc(doc(db,'conversations','learner','messages','spoof'),{...data,senderId:'admin'}))
 await assertFails(updateDoc(reference,{text:'تعديل غير مسموح'}))
 await assertFails(updateDoc(reference,{read:true}))
 await assertFails(setDoc(doc(db,'conversations','other','messages','message-2'),data))
})

test('disabled admin profiles cannot bypass the application gate through Firestore',async()=>{
 await env.withSecurityRulesDisabled(async(context)=>{
  await setDoc(doc(context.firestore(),'users','disabled-admin'),{role:'admin',status:'disabled'})
  await setDoc(doc(context.firestore(),'users','active-admin'),{role:'admin',status:'active'})
 })
 await assertFails(getDocs(collection(user('disabled-admin'),'users')))
 await assertSucceeds(getDocs(collection(user('active-admin'),'users')))
})